const thumb = (seed) => `https://picsum.photos/seed/strug-circle-${seed}/320/180`;

function friend(name, action, id, daysOrOpts = 0) {
	const opts = typeof daysOrOpts === "number" ? { daysAgo: daysOrOpts } : (daysOrOpts || {});
	const daysAgo = Number(opts.daysAgo) || 0;
	const hoursAgo = Number(opts.hoursAgo) || 0;
	const ms = (daysAgo * 86_400_000) + (hoursAgo * 3_600_000);
	return {
		profile_id: id,
		user_id: id + 100,
		display_name: name,
		handle: name.toLowerCase().replace(/\s+/g, ""),
		avatar_url: null,
		action,
		at: new Date(Date.now() - ms).toISOString(),
	};
}

